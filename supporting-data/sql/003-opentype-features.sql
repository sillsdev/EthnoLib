drop view if exists public.preferred_fonts;

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'font_support'
      and column_name = 'details'
  ) then
    alter table public.font_support rename column details to opentype_features;
  end if;
end $$;

alter table public.font_support
  alter column opentype_features type jsonb
  using nullif(btrim(opentype_features::text), '')::jsonb;

comment on column public.font_support.opentype_features is
  'OpenType feature settings for this font in this language, as SLDR records them '
  'on <sil:font features="...">: tag -> value, e.g. {"cv43": 0, "cv46": 1}. '
  'Includes stylistic sets (ssXX) as well as character variants (cvXX). The value '
  'selects one of the font''s own named forms, 1-based; 0 is the font''s default. '
  'Feature names live in the font, not here. null means the source named none.';

create or replace view public.preferred_fonts
  with (security_invoker = on) as
  select
    l.bcp47, f.family_name, fs.opentype_features,
    fs.id as font_support_id, fs.created_at
  from public.font_support fs
  join public.language l on l.id = fs.language_id
  join public.font f on f.id = fs.font_id
  where fs.rank = 'preferred'
  order by l.bcp47, fs.created_at;

create or replace view public.usable_fonts
  with (security_invoker = on) as
  select l.bcp47, f.family_name, fs.opentype_features, fs.rank,
         fs.id as font_support_id, fs.created_at
  from public.font_support fs
  join public.language l on l.id = fs.language_id
  join public.font f on f.id = fs.font_id
  where fs.rank <> 'deprecated'
    and public.font_support_is_approved(fs.id)
  order by l.bcp47, f.family_name;

