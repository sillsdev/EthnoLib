-- Rename font_support.details to opentype_features, give it a type that fits what
-- it holds, and fill in the settings SLDR already records.
--
-- WHY THE RENAME. The column was called `details` and documented as "the parts
-- that aren't boolean". What actually goes in it is one specific thing: the
-- OpenType feature settings SLDR records on `<sil:font features="...">`. Naming
-- it after the standard is deliberate. These are not only character variants
-- (cvXX) — stylistic sets (ssXX) are in the same attribute and matter just as
-- much, so a name like character_variants would exclude data already stored here.
--
-- WHY jsonb. SLDR writes `features="cv44=0 cv46=1"`, a set of tag/value pairs, so
-- an object of tag -> integer is the same statement in a form Postgres can index
-- and query ("which writing systems set cv43?"). The values are what SLDR gives,
-- untranslated: the integer selects one of the font's own named forms, 1-based,
-- and 0 means the font's default. What cv43 is called — "Capital Eng", in Charis
-- — lives in the font binary, not here. Turning a tag into something a reader can
-- act on is a separate job, and a harder one, because the same tag can mean
-- different things in different fonts.
--
-- WHY THE BACKFILL IS SQL. No table here has an UPDATE policy, on purpose: the
-- anonymous write path may only add rows. Stage 5 had already inserted 8,380
-- claims with this column null, and an importer cannot go back and fill them, so
-- this runs once with the service role. From here on the importer supplies the
-- value at insert time.
--
-- Generated from fontFeatureDefaults.json, snapshot 2026-08-15T14:05:54.276Z.
-- Re-runnable: the rename is guarded, the views are replaced, and the update is a
-- no-op once the values match.
--
-- Where two SLDR entries resolved to one writing system and disagreed:
--   kept man {"cv43":0} for man-Latn / Charis; ignored man-Latn-GN {"cv46":1}

